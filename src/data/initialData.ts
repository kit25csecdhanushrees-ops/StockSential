function makeHistory(currentQty: number, hourlyRate: number): StockHistoryPoint[] {
  const now = Date.now();
  const labels = ['-2.5h', '-2.0h', '-1.5h', '-1.0h', '-0.5h', 'Now'];
  return labels.map((label, index) => {
    const hoursAgo = (labels.length - 1 - index) * 0.5;
    const pastQty = Math.round((currentQty + hoursAgo * hourlyRate) * 10) / 10;
    return {
      timeLabel: label,
      timestamp: new Date(now - hoursAgo * 3600 * 1000).toISOString(),
      quantity: pastQty,
    };
  });
}

